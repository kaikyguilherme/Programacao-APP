// criando uma funcao 
function somar (a,b) {
    return a + b
}

//funcao para subtrair
function subtrair (c,d) {
    return c - d
}

//chamando funcao 
const soma = somar(2,3)

//chamando a funcao subtrair
const subt = subtrair(8,4)

//exibindo resultado
console.log(`Soma: ${soma}`)
console.log(`Subtração: ${subt}`)